using System.Reflection;
using Microsoft.Extensions.DependencyInjection;

namespace Splinter.Host;

// One independent, filtered JetStream ordered consumer per enabled Shard.
// All AMP / NATS types are late-bound: a changed beta signature disables live
// delivery and leaves the existing history-polling path operational.
public sealed class AmpConsoleEvents
{
    private const string Tenant = "_root";
    private const string Stream = "console";
    private readonly IServiceScopeFactory _scopes;
    private readonly Type? _providerType;
    private readonly MethodInfo? _getClient;
    private readonly Type? _historyType;
    private readonly MethodInfo? _toEntry;
    private readonly MethodInfo? _consoleSubject;
    private readonly MethodInfo? _lifecycleSubject;
    private readonly MethodInfo? _tenantToken;

    public AmpConsoleEvents(IServiceScopeFactory scopes)
    {
        _scopes = scopes;
        Assembly? shared = AppDomain.CurrentDomain.GetAssemblies()
            .FirstOrDefault(a => a.GetName().Name == "AmpShared");
        _providerType = shared?.GetType("AmpShared.MessageBus.NatsConnectionProvider", false);
        _getClient = _providerType?.GetMethod("GetClientAsync", [typeof(CancellationToken)]);
        Type? ns = shared?.GetType("AmpShared.Namespaces.Ns", false);
        _tenantToken = ns?.GetMethod("T", [typeof(string)]);
        _consoleSubject = ns?.GetMethod("ShardConsole", [typeof(string), typeof(Guid), typeof(string)]);
        _lifecycleSubject = ns?.GetMethod("ShardLifecycle", [typeof(string), typeof(Guid)]);
        _historyType = AppDomain.CurrentDomain.GetAssemblies()
            .FirstOrDefault(a => a.GetName().Name == "webapi")?
            .GetType("webapi.Hubs.ConsoleHistoryService", false);
        _toEntry = _historyType?.GetMethod("ToEntry", BindingFlags.Instance | BindingFlags.NonPublic,
            null, [typeof(string), typeof(string), typeof(DateTimeOffset), typeof(long)], null);
    }

    public bool Available => _providerType is not null && _getClient is not null &&
        _tenantToken is not null && _consoleSubject is not null && _lifecycleSubject is not null &&
        _historyType is not null && _toEntry is not null;

    // Compare directly with the exact NATS subjects generated by AMP's own
    // namespace helpers. Tokens can be normalised/encoded by AMP and must
    // never be reconstructed from an assumed tenant/Guid string format.
    public static bool SubjectMatches(string? subject, IReadOnlySet<string> allowedSubjects) =>
        !string.IsNullOrWhiteSpace(subject) && allowedSubjects.Contains(subject);

    // This small pure adapter makes the same AMP DTO parsing path testable
    // without loading NATS or executing AMP services in the regression suite.
    public static ConsoleEntry? FromAmpDto(object? dto)
    {
        if (dto is null) return null;
        try
        {
            return ConsoleHistoryBridge.ParsePage(new { Entries = new object[] { dto } })
                .FirstOrDefault();
        }
        catch (NotSupportedException) { return null; }
    }

    public async Task ListenAsync(Guid shardId, long? afterSequence,
        Func<ConsoleEntry, CancellationToken, Task> onLine, Action onReady,
        Action<string> onDiagnostic, CancellationToken ct)
    {
        if (shardId == Guid.Empty) throw new ArgumentException("A Shard ID is required.", nameof(shardId));
        if (!Available) throw new NotSupportedException("AMP console event interfaces are unavailable.");
        using IServiceScope scope = _scopes.CreateScope();
        object provider = scope.ServiceProvider.GetService(_providerType!) ??
            throw new NotSupportedException("AMP NATS connection provider is not registered.");
        object history = scope.ServiceProvider.GetService(_historyType!) ??
            throw new NotSupportedException("AMP console history service is not registered.");

        object client = await AwaitValueAsync(_getClient!.Invoke(provider, [ct]), ct).ConfigureAwait(false) ??
            throw new NotSupportedException("AMP NATS client is unavailable.");
        Assembly jetStream = AppDomain.CurrentDomain.GetAssemblies()
            .FirstOrDefault(a => a.GetName().Name == "NATS.Client.JetStream") ??
            Assembly.Load("NATS.Client.JetStream");
        Type extensions = jetStream.GetType("NATS.Net.NatsClientExtensions", true)!;
        // Both CreateJetStreamContext(INatsClient) and
        // CreateJetStreamContext(INatsConnection) can match a NatsConnection.
        // Bind the INatsClient overload used by AMP, rather than calling
        // SingleOrDefault on a set containing both valid overloads.
        Type clientContract = client.GetType().GetInterfaces()
            .FirstOrDefault(t => t.FullName == "NATS.Client.Core.INatsClient") ??
            throw new NotSupportedException("AMP NATS client does not expose INatsClient.");
        MethodInfo factory = SelectJetStreamContextFactory(
            extensions.GetMethods(BindingFlags.Public | BindingFlags.Static), clientContract);
        object js = factory.Invoke(null, [client]) ??
            throw new NotSupportedException("AMP returned no JetStream context.");

        // ConsoleHistoryService.GetPageAsync uses Ns.T(tenantId) before
        // passing that token to Ns.ShardConsole. Mirror the same contract.
        string tenantToken = _tenantToken!.Invoke(null, [Tenant]) as string ??
            throw new NotSupportedException("AMP returned no tenant subject token.");
        string[] subjects = new[] { "main", "update", "agent" }
            .Select(s => (string)_consoleSubject!.Invoke(null, [tenantToken, shardId, s])!).ToArray();
        subjects = [..subjects, (string)_lifecycleSubject!.Invoke(null, [tenantToken, shardId])!];
        if (subjects.Any(string.IsNullOrWhiteSpace) ||
            subjects.Distinct(StringComparer.Ordinal).Count() != subjects.Length)
            throw new NotSupportedException("AMP returned invalid or duplicate console subjects.");
        IReadOnlySet<string> allowedSubjects = new HashSet<string>(subjects, StringComparer.Ordinal);

        Type optsType = jetStream.GetType("NATS.Client.JetStream.NatsJSOrderedConsumerOpts", true)!;
        object opts = Activator.CreateInstance(optsType)!;
        PropertyInfo filter = optsType.GetProperty("FilterSubjects") ??
            throw new NotSupportedException("AMP JetStream subject filtering is unavailable.");
        filter.SetValue(opts, subjects);
        PropertyInfo policy = optsType.GetProperty("DeliverPolicy") ??
            throw new NotSupportedException("AMP JetStream deliver policy is unavailable.");
        bool resume = afterSequence is >= 0 and < long.MaxValue;
        policy.SetValue(opts, Enum.Parse(policy.PropertyType, resume ? "ByStartSequence" : "New"));
        if (resume)
        {
            PropertyInfo start = optsType.GetProperty("OptStartSeq") ??
                throw new NotSupportedException("AMP JetStream sequence positioning is unavailable.");
            start.SetValue(opts, checked((ulong)afterSequence!.Value + 1UL));
        }

        MethodInfo create = js.GetType().GetMethods(BindingFlags.Public | BindingFlags.Instance)
            .SingleOrDefault(m => m.Name == "CreateOrderedConsumerAsync" &&
                m.GetParameters().Length == 3 &&
                m.GetParameters()[0].ParameterType == typeof(string) &&
                m.GetParameters()[1].ParameterType == optsType &&
                m.GetParameters()[2].ParameterType == typeof(CancellationToken)) ??
            throw new NotSupportedException("AMP JetStream ordered consumer signature has changed.");
        object consumer = await AwaitValueAsync(create.Invoke(js, [Stream, opts, ct]), ct)
            .ConfigureAwait(false) ?? throw new NotSupportedException("AMP returned no ordered consumer.");
        MethodInfo consume = consumer.GetType().GetMethods(BindingFlags.Public | BindingFlags.Instance)
            .SingleOrDefault(m => m.Name == "ConsumeAsync" && m.IsGenericMethodDefinition &&
                m.GetGenericArguments().Length == 1 && m.GetParameters().Length == 3 &&
                m.GetParameters()[2].ParameterType == typeof(CancellationToken))?.MakeGenericMethod(typeof(string)) ??
            throw new NotSupportedException("AMP JetStream consumer signature has changed.");
        object stream = consume.Invoke(consumer, [null, null, ct]) ??
            throw new NotSupportedException("AMP returned no console event stream.");
        // NATS yields IAsyncEnumerable<INatsJSMsg<string>>. Select that
        // exact contract: an iterator may expose additional async enumerable
        // interfaces, making a generic Single(...) lookup ambiguous.
        Type msgType = jetStream.GetType("NATS.Client.JetStream.INatsJSMsg`1", true)!
            .MakeGenericType(typeof(string));
        Type streamInterface = SelectAsyncStreamInterface(stream.GetType(), msgType);
        Type itemType = msgType;
        Type enumeratorInterface = typeof(IAsyncEnumerator<>).MakeGenericType(itemType);
        object enumerator = streamInterface.GetMethod("GetAsyncEnumerator")!.Invoke(stream, [ct])!;
        try
        {
            onReady();
            bool reportedFirstNatsMessage = false;
            bool reportedFirstParsedLine = false;
            while (!ct.IsCancellationRequested)
            {
                object? moving = enumeratorInterface.GetMethod("MoveNextAsync")!.Invoke(enumerator, null);
                if (await AwaitValueAsync(moving, ct).ConfigureAwait(false) is not true) break;
                object? item = enumeratorInterface.GetProperty("Current")!.GetValue(enumerator);
                if (item is null) continue;
                Type type = item.GetType();
                string? subject = type.GetProperty("Subject")?.GetValue(item) as string;
                bool subjectAccepted = SubjectMatches(subject, allowedSubjects);
                if (!reportedFirstNatsMessage)
                {
                    reportedFirstNatsMessage = true;
                    onDiagnostic($"first NATS record received; AMP subject accepted={subjectAccepted}");
                }
                if (!subjectAccepted) continue;
                string? data = type.GetProperty("Data")?.GetValue(item) as string;
                if (string.IsNullOrEmpty(data) || data.Length > 65536) continue;
                object? metadata = type.GetProperty("Metadata")?.GetValue(item);
                object? sequence = metadata?.GetType().GetProperty("Sequence")?.GetValue(metadata);
                object? rawSeq = sequence?.GetType().GetProperty("Stream")?.GetValue(sequence);
                if (rawSeq is null) continue;
                ulong streamSeq = Convert.ToUInt64(rawSeq, System.Globalization.CultureInfo.InvariantCulture);
                if (streamSeq == 0 || streamSeq > long.MaxValue) continue;
                object? rawTime = metadata?.GetType().GetProperty("Timestamp")?.GetValue(metadata);
                DateTimeOffset timestamp = rawTime is DateTimeOffset instant ? instant : DateTimeOffset.UtcNow;
                // AMP already knows how to turn both structured console lines
                // and lifecycle markers into ConsoleLineDto; reuse that parser.
                object? entry = _toEntry!.Invoke(history, [subject!, data, timestamp, (long)streamSeq]);
                object? dto = entry?.GetType().GetProperty("Dto")?.GetValue(entry);
                ConsoleEntry? line = FromAmpDto(dto);
                if (line is not null)
                {
                    if (!reportedFirstParsedLine)
                    {
                        reportedFirstParsedLine = true;
                        onDiagnostic($"first console DTO parsed; seq={line.Sequence}; stream={line.StreamId ?? "(null)"}");
                    }
                    await onLine(line, ct).ConfigureAwait(false);
                }
            }
        }
        finally
        {
            if (enumerator is IAsyncDisposable disposable)
                await disposable.DisposeAsync().ConfigureAwait(false);
        }
    }

    // Exact overload resolution is essential here: the concrete NATS client
    // implements multiple interfaces accepted by the similarly named factory.
    internal static MethodInfo SelectJetStreamContextFactory(
        IEnumerable<MethodInfo> methods, Type clientContract)
    {
        ArgumentNullException.ThrowIfNull(methods);
        ArgumentNullException.ThrowIfNull(clientContract);
        MethodInfo[] matches = methods.Where(m =>
            m.IsPublic && m.IsStatic && m.Name == "CreateJetStreamContext" &&
            !m.ContainsGenericParameters &&
            m.GetParameters().Length == 1 &&
            m.GetParameters()[0].ParameterType == clientContract).ToArray();
        if (matches.Length != 1)
            throw new NotSupportedException(
                $"AMP JetStream INatsClient factory signature not unique (matches={matches.Length}).");
        return matches[0];
    }

    internal static Type SelectAsyncStreamInterface(Type streamType, Type messageType)
    {
        ArgumentNullException.ThrowIfNull(streamType);
        ArgumentNullException.ThrowIfNull(messageType);
        Type required = typeof(IAsyncEnumerable<>).MakeGenericType(messageType);
        if (!required.IsAssignableFrom(streamType))
            throw new NotSupportedException("AMP JetStream returned an unexpected console stream item type.");
        return required;
    }

    private static async Task<object?> AwaitValueAsync(object? pending, CancellationToken ct)
    {
        if (pending is Task task)
        {
            await task.WaitAsync(ct).ConfigureAwait(false);
            return task.GetType().GetProperty("Result")?.GetValue(task);
        }
        if (pending is null) throw new NotSupportedException("AMP returned no NATS operation.");
        MethodInfo? asTask = pending.GetType().GetMethod("AsTask", Type.EmptyTypes);
        if (asTask?.Invoke(pending, null) is Task converted)
        {
            await converted.WaitAsync(ct).ConfigureAwait(false);
            return converted.GetType().GetProperty("Result")?.GetValue(converted);
        }
        throw new NotSupportedException("AMP returned an unsupported NATS awaitable.");
    }
}
